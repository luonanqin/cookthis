function stripPlaces(name) {
  let n = String(name || '')
  for (const p of PLACE) {
    if (!p) continue
    while (n.includes(p)) n = n.split(p).join('')
  }
  n = n.replace(TRAILING_ABBR, '')
  n = n.replace(/(馅料|汤料|配菜|面剂|粉料|酱料|肉料|鱼料|干料|拼盘|浇头)/g, '')
  n = n.replace(/(料|配|剂|拼)$/g, '')
  n = n.replace(/羊肉肉$/, '羊肉')
  n = n.replace(/牛肉牛$/, '牛肉')
  n = n.replace(/\s+/g, '')
  return n
}

function cleanIngName(name, city) {
  if (ING_EXACT[name]) return ING_EXACT[name]
  let n = name
  if (city) {
    const base = city.replace(/市$/, '')
    n = n.split(base).join('')
  }
  n = stripPlaces(n)
  if (ING_EXACT[n]) return ING_EXACT[n]
  if (!n || n.length < 1) return name
  return n
}

function cleanRcpName(name, city) {
  if (RCP_EXACT[name]) return RCP_EXACT[name]
  let n = name
  if (city) {
    const base = city.replace(/市$/, '')
    if (n.endsWith(base)) n = n.slice(0, -base.length)
    n = n.split(base).join('')
  }
  n = stripPlaces(n)
  n = n.replace(/(家常|风味|浇头|配菜|风)$/g, '')
  if (RCP_EXACT[n]) return RCP_EXACT[n]
  if (!n || n.length < 2) return name
  return n
}


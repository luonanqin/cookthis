function cleanName(raw) {
  if (EXACT[raw]) return EXACT[raw]
  let n = raw
  // 保护含「文昌」「武昌」等固有菜名
  const protect = []
  n = n.replace(/文昌鸡|文昌鱼|武昌鱼|都昌/g, (m) => {
    protect.push(m)
    return `__P${protect.length - 1}__`
  })
  for (const s of CITY_SUFFIXES) {
    if (n.endsWith(s) && n.length > s.length + 1) {
      n = n.slice(0, -s.length)
      break
    }
  }
  n = n.replace(/__P(\d+)__/g, (_, i) => protect[Number(i)])
  n = n.replace(/浇头$|配菜$|家常$|风味$/g, '')
  return n || raw
}

function main() {
  const list = JSON.parse(fs.readFileSync(RCP_PATH, 'utf8'))
  const changes = []
  for (const r of list) {
    const next = cleanName(r.name)
    if (next !== r.name) {
      changes.push(`${r.name} → ${next}`)
      r.name = next
    }
  }
  fs.writeFileSync(RCP_PATH, JSON.stringify(list, null, 2) + '\n')
  console.log('Renamed', changes.length, 'recipes')
  changes.slice(0, 50).forEach((x) => console.log(' ', x))
  if (changes.length > 50) console.log(' ...', changes.length - 50, 'more')
}

main()

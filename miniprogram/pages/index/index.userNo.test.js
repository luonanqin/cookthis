'use strict'

const { describe, it } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const dir = __dirname
const js = fs.readFileSync(path.join(dir, 'index.js'), 'utf8')
const wxml = fs.readFileSync(path.join(dir, 'index.wxml'), 'utf8')
const wxss = fs.readFileSync(path.join(dir, 'index.wxss'), 'utf8')

describe('index first-launch userNo ceremony ①→②', () => {
  it('uses one mask with roll then steps, mask tap does not close', () => {
    assert.match(wxml, /showUserNoCeremony/)
    assert.match(wxml, /ceremony-phase-\{\{ceremonyPhase\}\}/)
    assert.match(wxml, /欢迎！第/)
    assert.match(wxml, /位大厨！/)
    assert.match(wxml, /ceremony-line/)
    assert.doesNotMatch(wxml, /欢迎加入/)
    assert.doesNotMatch(wxml, /ceremony-welcome-title|ceremony-final/)
    assert.match(wxml, /\{\{revealDisplay\}\}/)
    assert.match(wxss, /\.ceremony-line\s*\{[^}]*flex-direction:\s*row/)
    assert.match(wxss, /\.ceremony-roll\s*\{[^}]*--fs-brand|--color-primary/)
    assert.match(wxml, /使用说明/)
    assert.doesNotMatch(wxml, /勾选食材，生成搭配，按清单购买/)
    assert.match(wxml, /ceremony-step-index/)
    assert.match(wxml, /确认今日可选食材/)
    assert.match(wxml, /生成完整菜品搭配/)
    assert.match(wxml, /按清单采购回家做/)
    assert.match(wxml, /完善偏好/)
    assert.doesNotMatch(wxml, /去完善偏好/)
    assert.match(wxml, /先逛逛/)
    assert.match(wxml, /ceremony-actions/)
    assert.match(wxml, /catchtap="noop"/)
    assert.doesNotMatch(wxml, /bindtap="onCeremonyBrowseFirst".*mask|user-no-ceremony[^>]*bindtap="onCeremony/)
  })

  it('left-aligns guide title and numbered steps', () => {
    assert.match(wxss, /\.ceremony-steps-title\s*\{[^}]*text-align:\s*left/)
    assert.match(wxss, /\.ceremony-step-name\s*\{[^}]*text-align:\s*left/)
    assert.match(wxss, /\.ceremony-step-desc\s*\{[^}]*text-align:\s*left/)
    assert.match(wxss, /\.ceremony-step-index/)
    assert.match(wxss, /\.ceremony-steps-mark/)
    assert.match(wxss, /\.ceremony-step-line/)
    assert.match(wxml, />01</)
    assert.match(wxml, />02</)
    assert.match(wxml, />03</)
    assert.doesNotMatch(wxss, /\.ceremony-steps-sub/)
  })

  it('puts browse left and preference right in one row', () => {
    assert.match(wxss, /\.ceremony-actions\s*\{[^}]*flex-direction:\s*row/)
    const actions = wxml.match(/class="ceremony-actions"[\s\S]*?<\/view>/)
    assert.ok(actions)
    assert.match(actions[0], /先逛逛[\s\S]*完善偏好/)
  })

  it('starts from onShow, transitions without closing, acks only on CTAs', () => {
    assert.match(js, /_maybeStartUserNoCeremony/)
    assert.match(js, /_beginCeremonyTransition/)
    assert.match(js, /ceremonyPhase:\s*'transition'/)
    assert.match(js, /ceremonyPhase:\s*'steps'/)
    assert.match(js, /onCeremonyGoOnboarding/)
    assert.match(js, /onCeremonyBrowseFirst/)
    assert.match(js, /ackUserNoReveal/)
    assert.match(js, /user_no_reveal_steps/)
    assert.match(js, /user_no_reveal_ack[\s\S]*via/)
    assert.match(js, /_ackUserNoCeremony\('onboarding'\)/)
    assert.match(js, /_ackUserNoCeremony\('browse'\)/)
    assert.match(js, /pages\/onboarding\/onboarding/)
    assert.match(js, /cookthis_user_no_reveal_seen/)
    assert.match(js, /showUserNoCeremony/)
    assert.match(js, /goMarket[\s\S]*showUserNoCeremony/)
    assert.match(js, /onDebugReplayUserNoCeremony/)
    assert.match(js, /force:\s*true/)
    assert.match(wxml, /重播首启仪式 · 100000（测试）/)
    assert.match(js, /userNo:\s*100000/)
  })

  it('keeps the number visible and opens a drawer below it', () => {
    assert.match(wxss, /\.user-no-ceremony/)
    assert.match(wxss, /\.ceremony-drawer/)
    assert.match(wxss, /max-height/)
    assert.match(wxml, /ceremony-drawer/)
    assert.match(wxml, /ceremony-card/)
    // 序号区块始终在 DOM，不因进入 steps 而卸载
    assert.match(wxml, /ceremony-welcome/)
    assert.doesNotMatch(wxss, /\.ceremony-phase-steps \.ceremony-welcome\s*\{[^}]*opacity:\s*0/)
  })

  it('bursts confetti center-to-sides before opening the drawer', () => {
    assert.match(wxml, /ceremony-confetti/)
    assert.match(wxml, /showCeremonyConfetti/)
    assert.match(wxml, /ceremony-burst-\{\{item\.burst\}\}/)
    assert.match(js, /_playCeremonyConfetti/)
    assert.match(js, /_scheduleCeremonyConfettiAfterLabel/)
    assert.match(js, /buildCeremonyConfetti/)
    assert.match(js, /CEREMONY_CONFETTI_MS/)
    assert.match(js, /CEREMONY_LABEL_HOLD_MS/)
    assert.match(js, /_runCeremonyRoll[\s\S]*_scheduleCeremonyConfettiAfterLabel/)
    assert.match(js, /_scheduleCeremonyConfettiAfterLabel[\s\S]*_playCeremonyConfetti/)
    assert.match(js, /_playCeremonyConfetti[\s\S]*_beginCeremonyTransition/)
    assert.match(wxss, /\.ceremony-confetti/)
    assert.match(wxss, /ceremony-burst-l0/)
    assert.match(wxss, /ceremony-burst-r0/)
    assert.match(wxss, /translate3d\(-/)
    assert.match(wxss, /translate3d\(/)
  })
})

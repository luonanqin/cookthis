'use strict'

const { describe, it } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const dir = __dirname
const js = fs.readFileSync(path.join(dir, 'confirm.js'), 'utf8')
const wxml = fs.readFileSync(path.join(dir, 'confirm.wxml'), 'utf8')
const wxss = fs.readFileSync(path.join(dir, 'confirm.wxss'), 'utf8')

describe('confirm seasonal expand', () => {
  it('uses top sheet with mask and matching year-round header', () => {
    assert.match(wxml, /已选 \{\{seasonalCount\}\} \/ 共 \{\{seasonalTotal\}\}/)
    assert.match(wxml, /已选 \{\{yearRoundCount\}\} \/ 共 \{\{yearRoundTotal\}\}/)
    assert.match(wxml, /时令菜/)
    assert.match(wxml, /section-title">常见菜</)
    assert.match(wxml, /seasonalFlat/)
    assert.match(wxml, /onOpenSeasonalDrawer/)
    assert.match(wxml, /seasonalExpanded/)
    assert.match(wxml, /mask-season-top/)
    assert.match(wxml, /season-sheet-top/)
    assert.match(wxml, /onCloseSeasonalDrawer/)
    assert.match(wxml, /season-expand-link/)
    assert.match(wxml, />展开</)
    const scaleAt = wxml.indexOf('market-scale-entry')
    const seasonAt = wxml.indexOf('season-card')
    assert.ok(scaleAt >= 0 && seasonAt > scaleAt)
    assert.match(js, /flattenSeasonalGroups/)
    assert.match(js, /seasonalExpanded:\s*true/)
    assert.match(js, /onHeaderHeight/)
    assert.match(js, /headerHeight/)
    assert.match(wxml, /bind:heightchange="onHeaderHeight"/)
    assert.match(wxml, /top: \{\{headerHeight\}\}px/)
    assert.match(wxss, /season-preview/)
    assert.match(wxss, /mask-season-top/)
    assert.match(wxss, /z-index:\s*120/)
    assert.match(wxss, /season-sheet-top/)
    assert.match(wxml, /season-sheet-scroll/)
    const sheetAt = wxml.indexOf('season-sheet-top')
    const actionsAt = wxml.indexOf('season-actions')
    assert.ok(sheetAt >= 0 && actionsAt > sheetAt)
  })
})
